const METHOD = "CricField holds ball-by-ball cricket data and no fan survey, sentiment or social-media data. This article measures the cricket fans have experienced; statements about fans themselves are labelled hypotheses. Generated by scripts/editorial/engine.";
const noFanData = `The CricField warehouse holds no survey, sentiment or social-media data, so it cannot measure what fans feel. It can measure what they have watched.`;
const span = (a: { c: { firstYear: number } }) => `${a.c.firstYear}–2026`;
const pctOf = (k: number, n: number) => (n ? (k / n) * 100 : NaN);

function streaks(ms: MyMatch[]) {
  let w = 0, l = 0, bw = 0, bl = 0, lossRuns = 0;
  for (const m of ms.filter((x) => x.w != null)) {
    if (m.won) { w++; if (l >= 3) lossRuns++; l = 0; } else { l++; w = 0; }
    bw = Math.max(bw, w); bl = Math.max(bl, l);
  }
  if (l >= 3) lossRuns++;
  return { bw, bl, lossRuns };
}

