// Players who batted or bowled for the franchise, by season.
export function servers(a: Parameters<SlotSpec["build"]>[0]) {
  const sql = `SELECT pl.name, COUNT(DISTINCT x.y) seasons, MIN(x.y) first, MAX(x.y) last FROM (
      SELECT ${YEAR()} y, d.batter_id pid FROM deliveries d JOIN innings i ON i.innings_id = d.innings_id JOIN matches m ON m.match_id = d.match_id WHERE i.innings_number <= 2 AND i.batting_team_id IN ${a.T}
      UNION SELECT ${YEAR()} y, d.bowler_id pid FROM deliveries d JOIN innings i ON i.innings_id = d.innings_id JOIN matches m ON m.match_id = d.match_id WHERE i.innings_number <= 2 AND i.bowling_team_id IN ${a.T}) x
    JOIN players pl ON pl.player_id = x.pid GROUP BY pl.name ORDER BY seasons DESC, pl.name`;
  return { sql, rows: a.rows<{ name: string; seasons: number; first: number; last: number }>(sql) };
}

