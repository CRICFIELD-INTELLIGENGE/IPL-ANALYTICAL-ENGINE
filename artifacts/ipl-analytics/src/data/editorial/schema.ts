// CricField Dugout — article schema v2 (the 1,000-article programme).
//
// One article = one JSON file under src/data/editorial/articles/<franchise>/<id>.json,
// paired with a generated evidence file under src/data/editorial/evidence/<franchise>/<id>.json.
// Prose never carries a hand-typed statistic: numbers enter the text only through
// {{ev:<metricId>}} tokens that resolve against the evidence file, which records the
// dataset, filters, sample size, SQL and validation for every value.
//
// Statuses: draft → review → published. Only "published" articles ship in a public build
// (see vite.config.ts → editorialArticleRelease); "review" articles render on localhost only.

import { z } from "zod";

export const EDITORIAL_ASPECTS = [
  { number: 1, id: "batting", name: "Batting Intelligence" },
  { number: 2, id: "bowling-fielding", name: "Bowling & Fielding Science" },
  { number: 3, id: "tactical", name: "Tactical & Match Intelligence" },
  { number: 4, id: "auction-economics", name: "Auction & Squad Economics" },
  { number: 5, id: "business", name: "Franchise Business & Revenue" },
  { number: 6, id: "fan-culture", name: "Fan Psychology & Culture" },
  { number: 7, id: "history", name: "History, Legacy & Turning Points" },
  { number: 8, id: "scouting", name: "Player Development & Scouting" },
  { number: 9, id: "data-science", name: "Data Science & Predictive Analytics" },
  { number: 10, id: "future", name: "Future Strategy & Innovation" },
] as const;

export type EditorialAspectId = (typeof EDITORIAL_ASPECTS)[number]["id"];
const ASPECT_IDS = EDITORIAL_ASPECTS.map((a) => a.id) as [EditorialAspectId, ...EditorialAspectId[]];

export const FRANCHISE_CODES = ["CSK", "MI", "RCB", "KKR", "SRH", "RR", "DC", "PBKS", "GT", "LSG"] as const;
export type FranchiseCode = (typeof FRANCHISE_CODES)[number];

export const EDITORIAL_AUTHOR = "CricField Editorial Desk";
export const ARTICLE_STATUSES = ["draft", "review", "published"] as const;
export type ArticleStatus = (typeof ARTICLE_STATUSES)[number];

/** Section roles are fixed; headings are written per article. */
export const SECTION_ROLES = ["hook", "evidence", "tactical", "counterargument", "verdict"] as const;
export type SectionRole = (typeof SECTION_ROLES)[number];

// ── Plan (titles-1000.json) ────────────────────────────────────────────────────

export const planEntrySchema = z.object({
  planId: z.string().regex(/^cf-[a-z]+-\d{3}$/),
  franchise: z.enum(FRANCHISE_CODES),
  franchiseName: z.string(),
  aspect: z.enum(ASPECT_IDS),
  aspectName: z.string(),
  aspectNumber: z.number().int().min(1).max(10),
  articleInAspect: z.number().int().min(1).max(10),
  globalNumber: z.number().int().min(1).max(1000),
  franchiseNumber: z.number().int().min(1).max(100),
  title: z.string().min(10),
  slug: z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/),
  sourceStatus: z.string(),
});
export type PlanEntry = z.infer<typeof planEntrySchema>;

// ── Evidence (generated by scripts/editorial/compute-evidence-*.ts) ─────────────

export const evidenceMetricSchema = z.object({
  value: z.union([z.number(), z.string()]),
  display: z.string(),
  label: z.string(),
  unit: z.string().optional(),
  dataset: z.string(),
  filters: z.string(),
  sampleSize: z.object({ n: z.number().int().nonnegative(), unit: z.string() }),
  query: z.string(),
  validation: z.object({ method: z.string(), passed: z.boolean(), detail: z.string().optional() }),
});
export type EvidenceMetric = z.infer<typeof evidenceMetricSchema>;

export const evidenceTableSchema = z.object({
  label: z.string(),
  dataset: z.string(),
  filters: z.string(),
  sampleSize: z.object({ n: z.number().int().nonnegative(), unit: z.string() }),
  query: z.string(),
  rows: z.array(z.record(z.union([z.string(), z.number(), z.null()]))),
});
export type EvidenceTable = z.infer<typeof evidenceTableSchema>;

export const evidenceFileSchema = z.object({
  articleId: z.string(),
  generatedAt: z.string(),
  generator: z.string(),
  database: z.object({ file: z.string(), matches: z.number(), deliveries: z.number(), lastMatchDate: z.string() }),
  metrics: z.record(evidenceMetricSchema),
  tables: z.record(evidenceTableSchema),
});
export type EvidenceFile = z.infer<typeof evidenceFileSchema>;

// ── Article ───────────────────────────────────────────────────────────────────

const sectionSchema = z.object({
  id: z.enum(["s1", "s2", "s3", "s4", "s5"]),
  role: z.enum(SECTION_ROLES),
  heading: z.string().min(4),
  /** Paragraphs. Statistics only via {{ev:metricId}}; external claims via {{src:sourceId}}; hypotheses via {{hyp:id}}. */
  body: z.array(z.string().min(8)).min(2),
  chartIds: z.array(z.string()).optional(),
  pullQuote: z.string().optional(),
});

export const chartSchema = z.object({
  id: z.string(),
  type: z.enum(["bar", "column", "line", "stacked-bar", "scatter"]),
  title: z.string(),
  subtitle: z.string().optional(),
  /** Evidence table the chart is drawn from. */
  table: z.string(),
  xKey: z.string(),
  series: z.array(z.object({ key: z.string(), label: z.string(), color: z.string().optional() })).min(1),
  xLabel: z.string().optional(),
  unit: z.string(),
  /** Plain-language summary for screen readers and as the visible takeaway. */
  takeaway: z.string(),
  ariaLabel: z.string(),
  referenceLine: z.object({ metric: z.string(), label: z.string() }).optional(),
});
export type ArticleChart = z.infer<typeof chartSchema>;

export const sourceSchema = z.object({
  id: z.string(),
  kind: z.enum(["cricfield-dataset", "external-report", "official", "academic", "news"]),
  title: z.string(),
  publisher: z.string(),
  url: z.string().url().optional(),
  published: z.string().optional(),
  accessed: z.string().optional(),
  note: z.string().optional(),
});
export type ArticleSource = z.infer<typeof sourceSchema>;

export const hypothesisSchema = z.object({
  id: z.string(),
  statement: z.string(),
  whyUnverified: z.string(),
  howToTest: z.string(),
});

export const imageBriefSchema = z.object({
  slot: z.enum(["hero", "s1", "s2", "s3", "s4", "s5"]),
  narrative: z.string(),
  wanted: z.string(),
});

export const videoRefSchema = z.object({
  catalogueId: z.string(),
  afterSection: z.enum(["s1", "s2", "s3", "s4", "s5"]),
  why: z.string(),
});

export const articleSchema = z.object({
  schemaVersion: z.literal(2),
  id: z.string().regex(/^cf-[a-z]+-\d{3}$/),
  planId: z.string(),
  franchise: z.enum(FRANCHISE_CODES),
  aspect: z.enum(ASPECT_IDS),
  title: z.string(),
  slug: z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/),
  /** When the article revises a legacy Dugout article, its URL is kept. */
  supersedes: z.object({ legacyId: z.string(), legacySlug: z.string(), decision: z.enum(["revise", "reuse"]) }).optional(),
  dek: z.string().min(20),
  excerpt: z.string().min(20),
  author: z.literal(EDITORIAL_AUTHOR),
  publishedDate: z.string().regex(/^\d{4}-\d{2}-\d{2}$/),
  updatedDate: z.string().regex(/^\d{4}-\d{2}-\d{2}$/).optional(),
  status: z.enum(ARTICLE_STATUSES),
  /** Human editorial sign-off. Required for "published"; independent of any image's rights status. */
  editorialReview: z
    .object({ reviewedBy: z.string().min(2), reviewedAt: z.string().regex(/^\d{4}-\d{2}-\d{2}/), approved: z.boolean(), notes: z.string().optional() })
    .optional(),
  featured: z.boolean().default(false),
  storyType: z.enum(["investigation", "player-story", "tactical", "archive", "explainer"]),
  teams: z.array(z.string()).min(1),
  players: z.array(z.string()),
  seasons: z.array(z.string()),
  keyTakeaways: z.array(z.string()).min(2).max(5),
  sections: z.array(sectionSchema).length(5),
  charts: z.array(chartSchema),
  sources: z.array(sourceSchema).min(1),
  hypotheses: z.array(hypothesisSchema).default([]),
  /** Numerals allowed in prose without an evidence token (rules of the game, titles). Each needs a reason. */
  literalNumbers: z.array(z.object({ text: z.string(), reason: z.string() })).default([]),
  imageBriefs: z.array(imageBriefSchema),
  videos: z.array(videoRefSchema).default([]),
  related: z.array(z.string()).default([]),
  seo: z.object({ metaTitle: z.string().max(70), metaDescription: z.string().min(70).max(170) }),
  methodology: z.string().min(40),
  /** "engine:v1" for articles produced by scripts/editorial/engine; absent for hand-written articles. */
  generator: z.string().optional(),
});
export type ArticleV2 = z.infer<typeof articleSchema>;

/** Lightweight card record kept in src/data/editorial/index.json (generated). */
export const indexEntrySchema = z.object({
  id: z.string(),
  franchise: z.enum(FRANCHISE_CODES),
  aspect: z.enum(ASPECT_IDS),
  title: z.string(),
  slug: z.string(),
  dek: z.string(),
  status: z.enum(ARTICLE_STATUSES),
  storyType: z.string(),
  featured: z.boolean(),
  publishedDate: z.string(),
  readMinutes: z.number(),
  players: z.array(z.string()),
  seasons: z.array(z.string()),
  headlineStat: z.object({ label: z.string(), display: z.string() }).optional(),
  supersedes: z.string().optional(),
});
export type IndexEntry = z.infer<typeof indexEntrySchema>;

export const TOKEN_RE = /\{\{(ev|src|hyp):([a-z0-9-]+)\}\}/gi;
