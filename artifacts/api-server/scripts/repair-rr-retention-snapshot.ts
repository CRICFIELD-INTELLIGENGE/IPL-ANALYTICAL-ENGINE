import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import assert from "node:assert/strict";
import {getRegistry} from "../src/services/intelligence/identity";
import {bestSide} from "../src/services/intelligence/squad-optimizer";
import strategy from "../data/rr-2027-predictions.json";
const dir = path.resolve("data/intelligence");
const pointer = JSON.parse(fs.readFileSync(path.join(dir,"current.json"),"utf8"));
const currentSnapshot = JSON.parse(fs.readFileSync(path.join(dir,pointer.version,"snapshot.json"),"utf8"));
const originalVersion = currentSnapshot.dataCorrections?.kind === "identity-and-contract-repair" ? currentSnapshot.dataCorrections.sourceVersion : pointer.version;
const snapshot = JSON.parse(fs.readFileSync(path.join(dir,originalVersion,"snapshot.json"),"utf8"));
const target = snapshot.players.find((p: any) => p.id === "cs:470f446b");
assert.ok(target?.retentionV2?.projection && target.retentionV2.seasons.some((s: any) => s.season === 2025) && target.retentionV2.seasons.some((s: any) => s.season === 2026), "Vaibhav must have genuine recorded history before merging");
const stubId = "sq:vaibhav-sooryavanshi|india";
const normalize = (n: string) => n.toLowerCase().replace(/[^a-z]/g, "").replace("suryavanshi", "sooryavanshi").replace("amanrao", "amanraoperala").replace("peralaperala", "perala").replace("mdshanaka", "dasunshanaka");
snapshot.players = snapshot.players.filter((p: any) => p.id !== stubId);
const roles: Record<string,string> = {BAT:"batter",WK:"wicketkeeper",ALL:"all-rounder",BOWL:"bowler"};
const registry = getRegistry();
const squad = JSON.parse(fs.readFileSync(path.resolve("data/squads-by-season.json"),"utf8"))["2026"]["Rajasthan Royals"];
for (const p of snapshot.players) {
 if (p.team !== "RR") continue;
 const source = squad.find((r: any) => r.cricsheetName === p.name || r.name === p.name);
 const call = strategy.players.find(r => r.rosterStatus === "current-roster" && [p.name,source?.name ?? "", ...(registry.byCanonical.get(p.id)?.aliases ?? [])].some(name => [r.name, ...(r.aliases ?? [])].some(alias => normalize(name) === normalize(alias))));
 if (!call) continue;
 p.contractLakh = call.contractLakh;
 p.contractSource = call.contractSource;
 p.overseas = call.overseas;
 p.role = roles[call.role]; p.listedRole = p.role;
 p.candidate.overseas = call.overseas;
 p.candidate.keeper = call.role === "WK";
}
assert.equal(snapshot.players.filter((p: any) => p.team === "RR" && (p.id === target.id || p.id === stubId)).length,1);
assert.equal(target.contractLakh,110);
// Replace stale references to the duplicate in published team membership and fit explanations.
for (const p of snapshot.players) for (const f of p.fit ?? []) if (f.replaces) f.replaces = [...new Set(f.replaces.map((id: string) => id === stubId ? target.id : id))];
const rr = snapshot.players.filter((p: any) => p.team === "RR");
const side = bestSide(rr.map((p: any) => p.candidate));
const report = snapshot.teams.RR;
Object.assign(report,{squadSize:rr.length,overseasInSquad:rr.filter((p:any)=>p.overseas).length,contractLakh:rr.reduce((sum:number,p:any)=>sum+(p.contractLakh??0),0),strength:side.strength,feasible:side.feasible,composition:side.composition,gaps:side.gaps,xii:side.xii.map(p=>({id:p.id,name:p.name,rar:p.evidence?p.rar:null,overseas:p.overseas,keeper:p.keeper,evidence:p.evidence})),bench:side.bench.map(p=>({id:p.id,name:p.name,rar:p.evidence?p.rar:null,overseas:p.overseas,keeper:p.keeper,evidence:p.evidence}))});
const corrections = {kind:"identity-and-contract-repair",sourceVersion:originalVersion,source:"User-supplied RR mapping, 2026-11-06; existing Cricsheet warehouse history",mergedIds:{[stubId]:target.id},note:"No performance values or model probabilities were invented or retrained. Shanaka INR 2 Cr is user-supplied and unverified. Core locks are editorial commitments, not official announcements."};
const body = {...snapshot, dataCorrections:corrections};
delete body.version;
const version = `cf-intel-2026.${crypto.createHash("sha256").update(JSON.stringify(body)).digest("hex").slice(0,10)}`;
const destination = path.join(dir,version);
fs.mkdirSync(destination,{recursive:true});
fs.writeFileSync(path.join(destination,"snapshot.json"),JSON.stringify({version,...body}));
fs.writeFileSync(path.join(dir,"current.json"),JSON.stringify({version,publishedAt:new Date().toISOString()},null,2));
console.log(JSON.stringify({version,sourceVersion:originalVersion,rrPlayers:rr.length,vaibhav:{id:target.id,contractLakh:target.contractLakh,seasons:target.retentionV2.projection.seasonsUsed},contractLakh:report.contractLakh}));
