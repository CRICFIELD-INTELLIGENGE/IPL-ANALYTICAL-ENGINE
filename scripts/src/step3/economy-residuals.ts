// Step 3 — document the deliveries where the corrected warehouse formula still differs from Cricsheet.
//
//   tsx src/step3/economy-residuals.ts --out docs/global-data-engine/step3/economy-residuals.md
//
// Reads the raw Cricsheet JSON the site ships (lib/cricket-data/raw) and the warehouse (sqlite.db, read-only).
// For every regular-innings delivery with more than one no-ball run, or a wide with penalty runs, it finds the
// matching warehouse row (same match, innings and position in the innings) and compares what each charges
// the bowler. It then lists every bowler whose career total still differs.

import fs from "node:fs";
import path from "node:path";
import { DatabaseSync } from "node:sqlite";
import { IPL_RAW_DIR, REPO, parseArgs } from "../global/paths";

type Any = any; // eslint-disable-line @typescript-eslint/no-explicit-any
const { values } = parseArgs(process.argv.slice(2));
const ipl = new DatabaseSync(path.join(REPO, "sqlite.db"), { readOnly: true });
const nameOf = new Map((ipl.prepare("SELECT player_id, name FROM players").all() as Any[]).map((r) => [r.player_id, r.name]));
const pidOf = new Map((ipl.prepare("SELECT cricsheet_id, player_id FROM players").all() as Any[]).map((r) => [r.cricsheet_id, r.player_id]));
const rowsOf = ipl.prepare(`SELECT d.delivery_id, d.over_num, d.batter_runs, d.extra_runs, d.total_runs, d.is_wide, d.is_noball, d.bowler_id
  FROM deliveries d JOIN innings i ON i.innings_id = d.innings_id WHERE d.match_id = ? AND i.innings_number = ? ORDER BY d.delivery_id`);
const formula = (r: Any) => r.batter_runs + (r.is_wide ? r.extra_runs : 0) + (r.is_noball ? 1 : 0);

const cases: Any[] = [];
const truth = new Map<number, number>(), charged = new Map<number, number>();
for (const f of fs.readdirSync(IPL_RAW_DIR).filter((x) => x.endsWith(".json")).sort()) {
  const m = JSON.parse(fs.readFileSync(path.join(IPL_RAW_DIR, f), "utf8"));
  const id = f.replace(".json", "");
  (m.innings as Any[]).slice(0, 2).forEach((inn: Any, ii: number) => {
    if (inn.super_over) return;
    const wh = rowsOf.all(id, ii + 1) as Any[];
    let k = 0;
    for (const ov of inn.overs ?? []) ov.deliveries.forEach((d: Any, seq: number) => {
      const e = d.extras ?? {};
      const cs = d.runs.batter + (e.wides ?? 0) + (e.noballs ?? 0);
      const pid = pidOf.get(m.info.registry.people[d.bowler]);
      const w = wh[k++];
      if (pid != null) { truth.set(pid, (truth.get(pid) ?? 0) + cs); charged.set(pid, (charged.get(pid) ?? 0) + (w ? formula(w) : 0)); }
      if ((e.noballs ?? 0) > 1 || ((e.wides ?? 0) > 0 && (e.penalty ?? 0) > 0)) {
        cases.push({
          match: id, date: m.info.dates[0], season: m.info.season, teams: m.info.teams.join(" v "), innings: ii + 1, ball: `${ov.over}.${seq + 1}`,
          bowler: d.bowler, batter: d.batter, cricsheetExtras: JSON.stringify(e), runsBatter: d.runs.batter, cricsheetCharged: cs,
          warehouse: w ? `extra_runs ${w.extra_runs}, is_wide ${w.is_wide}, is_noball ${w.is_noball}` : "not found",
          warehouseAligned: w ? w.total_runs === d.runs.total && w.batter_runs === d.runs.batter : false,
          formulaCharged: w ? formula(w) : null,
          kind: (e.noballs ?? 0) > 1 ? `${e.noballs} no-ball runs` : `wide + ${e.penalty} penalty`,
        });
      }
    });
  });
}

const bowlers = [...truth.keys()].filter((p) => truth.get(p) !== charged.get(p)).map((p) => ({ name: nameOf.get(p), pid: p, truth: truth.get(p)!, charged: charged.get(p)!, diff: charged.get(p)! - truth.get(p)! }))
  .sort((a, b) => a.diff - b.diff);
const net = cases.reduce((s, c) => s + (c.formulaCharged - c.cricsheetCharged), 0);
const L = [
  "# Economy fix — remaining discrepancies (documented, not resolved)", "",
  `Generated by \`scripts/src/step3/economy-residuals.ts\` from the raw Cricsheet files and \`sqlite.db\`. After the economy patch, the warehouse charges bowlers **${net} runs** ` +
  `different from Cricsheet across IPL 2008–2026, on **${cases.length} deliveries**, affecting **${bowlers.length} bowlers**. Every other bowler's career runs conceded now equal the Cricsheet recount exactly.`, "",
  "## Why these deliveries cannot be fixed with the current warehouse", "",
  "- `sqlite.db` stores, for each delivery, only the total `extra_runs` plus `is_wide` / `is_noball` flags (and bye / leg-bye / penalty flags that were never populated). It does not store how the extras split between no-balls, byes, leg-byes and penalties.",
  "- **Multi-run no-balls**: Cricsheet records several no-ball runs on one delivery (e.g. `noballs: 5`). The project's definition — the same one the site's static JSON uses — charges all no-ball runs to the bowler. The warehouse cannot tell `5 no-ball runs` from `1 no-ball + 4 byes`, so the formula charges one run.",
  "- **Wide with penalty runs**: the warehouse cannot separate the 5 penalty runs from the wide, so the formula charges all six; Cricsheet charges only the wide.",
  "- An exact fix needs the per-type extras stored in the warehouse (schema/data change, not part of this patch). `global.db` already stores them per delivery, which is how this list was cross-checked.", "",
  "## The deliveries", "",
  "| Match | Date | Season | Teams | Inns | Over.ball | Bowler | Batter | Cricsheet extras | Kind | Cricsheet charges | Formula charges | Difference | Warehouse row | Row aligned |",
  "|---|---|---|---|---:|---|---|---|---|---|---:|---:|---:|---|---|",
  ...cases.map((c) => `| ${c.match} | ${c.date} | ${c.season} | ${c.teams} | ${c.innings} | ${c.ball} | ${c.bowler} | ${c.batter} | \`${c.cricsheetExtras}\` | ${c.kind} | ${c.cricsheetCharged} | ${c.formulaCharged} | ${c.formulaCharged - c.cricsheetCharged} | ${c.warehouse} | ${c.warehouseAligned ? "yes" : "NO"} |`),
  "", "## Bowlers whose career runs conceded still differ", "",
  "| Bowler | Cricsheet total | Warehouse (patched) | Difference |", "|---|---:|---:|---:|",
  ...bowlers.map((b) => `| ${b.name} | ${b.truth.toLocaleString("en-US")} | ${b.charged.toLocaleString("en-US")} | ${b.diff > 0 ? "+" : ""}${b.diff} |`),
  "", `Largest effect on an economy rate: ${bowlers.length ? bowlers.map((b) => ({ ...b, pct: (100 * Math.abs(b.diff)) / b.truth })).sort((a, b) => b.pct - a.pct)[0].name : "—"} ` +
  `(${bowlers.length ? (bowlers.map((b) => (100 * Math.abs(b.diff)) / b.truth).sort((a, b) => b - a)[0]).toFixed(2) : 0}% of career runs conceded).`, "",
];
fs.writeFileSync(values.get("out") ?? "economy-residuals.md", L.join("\n") + "\n");
console.log(`${cases.length} deliveries, ${bowlers.length} bowlers, net ${net} runs; all rows aligned: ${cases.every((c) => c.warehouseAligned)}`);
