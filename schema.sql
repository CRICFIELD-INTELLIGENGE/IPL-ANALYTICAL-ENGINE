-- PostgreSQL Database Schema for IPL Cricket Analytics Engine

-- -----------------------------------------------------------------------------
-- DIMENSION TABLES
-- -----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS teams (
    team_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) UNIQUE NOT NULL,
    short_name VARCHAR(10) NOT NULL,
    color VARCHAR(20) NOT NULL,
    titles INT DEFAULT 0
);

CREATE TABLE IF NOT EXISTS players (
    player_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) UNIQUE NOT NULL,
    role VARCHAR(50),
    country VARCHAR(100),
    batting_style VARCHAR(50),
    bowling_style VARCHAR(50),
    image_url VARCHAR(255),
    form INT,
    clutch INT,
    versatility INT,
    expected_value NUMERIC(5, 2), -- expected value in Crores
    rarity VARCHAR(20) DEFAULT 'Standard',
    status VARCHAR(20) DEFAULT 'POOL' -- POOL, SOLD, UNSOLD, ACTIVE
);

CREATE TABLE IF NOT EXISTS venues (
    venue_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) UNIQUE NOT NULL,
    city VARCHAR(100),
    pitch_type VARCHAR(50) DEFAULT 'Balanced'
);

CREATE TABLE IF NOT EXISTS seasons (
    season_id VARCHAR(10) PRIMARY KEY, -- e.g., '2008', '2026'
    champion_team_id INT REFERENCES teams(team_id) ON DELETE SET NULL,
    runner_up_team_id INT REFERENCES teams(team_id) ON DELETE SET NULL,
    mvp_player_id INT REFERENCES players(player_id) ON DELETE SET NULL
);

-- -----------------------------------------------------------------------------
-- FACT TABLES
-- -----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS matches (
    match_id VARCHAR(50) PRIMARY KEY, -- Cricsheet ID, e.g., '335982'
    season_id VARCHAR(10) REFERENCES seasons(season_id),
    date DATE,
    venue_id INT REFERENCES venues(venue_id),
    team1_id INT REFERENCES teams(team_id),
    team2_id INT REFERENCES teams(team_id),
    toss_winner_id INT REFERENCES teams(team_id),
    toss_decision VARCHAR(10), -- 'bat' or 'field'
    winner_id INT REFERENCES teams(team_id) ON DELETE SET NULL,
    margin_type VARCHAR(20), -- 'runs', 'wickets', 'tie', 'no result'
    margin_value INT,
    match_type VARCHAR(50), -- 'League', 'Qualifier', 'Eliminator', 'Final'
    player_of_match_id INT REFERENCES players(player_id) ON DELETE SET NULL,
    status VARCHAR(20) DEFAULT 'Finished' -- 'Finished', 'In Progress', 'Upcoming'
);

CREATE TABLE IF NOT EXISTS innings (
    innings_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id VARCHAR(50) REFERENCES matches(match_id) ON DELETE CASCADE,
    innings_number INT NOT NULL, -- 1 or 2
    batting_team_id INT REFERENCES teams(team_id),
    bowling_team_id INT REFERENCES teams(team_id),
    runs INT DEFAULT 0,
    wickets INT DEFAULT 0,
    overs NUMERIC(4, 2) DEFAULT 0.0,
    CONSTRAINT unique_innings_per_match UNIQUE (match_id, innings_number)
);

CREATE TABLE IF NOT EXISTS deliveries (
    delivery_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id VARCHAR(50) REFERENCES matches(match_id) ON DELETE CASCADE,
    innings_id INT REFERENCES innings(innings_id) ON DELETE CASCADE,
    over_num INT NOT NULL, -- 0 to 19
    ball_num INT NOT NULL, -- 1-indexed ball in the over
    batter_id INT REFERENCES players(player_id),
    bowler_id INT REFERENCES players(player_id),
    non_striker_id INT REFERENCES players(player_id),
    batter_runs INT DEFAULT 0,
    extra_runs INT DEFAULT 0,
    total_runs INT DEFAULT 0,
    is_wide BOOLEAN DEFAULT FALSE,
    is_noball BOOLEAN DEFAULT FALSE,
    is_bye BOOLEAN DEFAULT FALSE,
    is_legbye BOOLEAN DEFAULT FALSE,
    is_penalty BOOLEAN DEFAULT FALSE,
    is_boundary BOOLEAN DEFAULT FALSE, -- batter_runs = 4 or 6
    delivery_type VARCHAR(50), -- e.g., 'Yorker', 'Short Ball', 'Off-Break'
    scoring_area VARCHAR(50), -- e.g., 'Cover', 'Fine Leg'
    pressure_state VARCHAR(20) DEFAULT 'Standard', -- 'Standard', 'High', 'Clutch', 'Playoff'
    phase VARCHAR(20),
    is_dot_ball BOOLEAN NOT NULL DEFAULT FALSE,
    is_death_over BOOLEAN NOT NULL DEFAULT FALSE,
    is_powerplay BOOLEAN NOT NULL DEFAULT FALSE,
    current_rr DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    required_rr DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    wickets_left INTEGER NOT NULL DEFAULT 10
);

CREATE TABLE IF NOT EXISTS dismissals (
    dismissal_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id INT REFERENCES deliveries(delivery_id) ON DELETE CASCADE,
    player_out_id INT REFERENCES players(player_id),
    kind VARCHAR(50) NOT NULL, -- 'caught', 'bowled', 'lbw', etc.
    fielder_id INT REFERENCES players(player_id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS partnerships (
    partnership_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id VARCHAR(50) REFERENCES matches(match_id) ON DELETE CASCADE,
    innings_id INT REFERENCES innings(innings_id) ON DELETE CASCADE,
    batter1_id INT REFERENCES players(player_id),
    batter2_id INT REFERENCES players(player_id),
    runs INT DEFAULT 0,
    balls INT DEFAULT 0,
    unbroken BOOLEAN DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS clutch_index (
    player_id INTEGER PRIMARY KEY REFERENCES players(player_id) ON DELETE CASCADE,
    clutch_score DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    clutch_runs INTEGER NOT NULL DEFAULT 0,
    clutch_wickets INTEGER NOT NULL DEFAULT 0,
    strike_rate DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    economy DOUBLE PRECISION NOT NULL DEFAULT 0.0
);

CREATE TABLE IF NOT EXISTS momentum_tracker (
    tracker_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id VARCHAR(50) REFERENCES matches(match_id) ON DELETE CASCADE NOT NULL,
    innings_number INTEGER NOT NULL,
    over_num INTEGER NOT NULL,
    runs INTEGER NOT NULL DEFAULT 0,
    wickets INTEGER NOT NULL DEFAULT 0,
    momentum_score DOUBLE PRECISION NOT NULL DEFAULT 0.0
);

CREATE TABLE IF NOT EXISTS partnership_stats (
    partnership_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id VARCHAR(50) REFERENCES matches(match_id) ON DELETE CASCADE NOT NULL,
    batter1_id INTEGER REFERENCES players(player_id) NOT NULL,
    batter2_id INTEGER REFERENCES players(player_id) NOT NULL,
    total_runs INTEGER NOT NULL DEFAULT 0,
    total_balls INTEGER NOT NULL DEFAULT 0,
    century_partnerships INTEGER NOT NULL DEFAULT 0,
    half_century_partnerships INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS player_team_history (
    history_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id INTEGER REFERENCES players(player_id) ON DELETE CASCADE NOT NULL,
    team_id INTEGER REFERENCES teams(team_id) ON DELETE CASCADE NOT NULL,
    season_id VARCHAR(10) REFERENCES seasons(season_id) ON DELETE CASCADE NOT NULL,
    start_season_id VARCHAR(10) REFERENCES seasons(season_id) ON DELETE SET NULL,
    end_season_id VARCHAR(10) REFERENCES seasons(season_id) ON DELETE SET NULL,
    current_team BOOLEAN DEFAULT FALSE NOT NULL,
    squad_role VARCHAR(50),
    franchise_role VARCHAR(50),
    representation_scope VARCHAR(30) DEFAULT 'franchise-legacy' NOT NULL,
    CONSTRAINT unique_player_team_season UNIQUE (player_id, team_id, season_id)
);

CREATE TABLE IF NOT EXISTS current_squad (
    squad_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id INTEGER REFERENCES players(player_id) ON DELETE CASCADE NOT NULL,
    team_id INTEGER REFERENCES teams(team_id) ON DELETE CASCADE NOT NULL,
    season_id VARCHAR(10) REFERENCES seasons(season_id) ON DELETE CASCADE,
    role VARCHAR(50),
    designation VARCHAR(50),
    CONSTRAINT unique_player_squad UNIQUE (player_id, team_id)
);

-- -----------------------------------------------------------------------------
-- PRECOMPUTED ANALYTICS TABLES
-- -----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS player_career_stats (
    player_id INT PRIMARY KEY REFERENCES players(player_id) ON DELETE CASCADE,
    role VARCHAR(50),
    matches INT DEFAULT 0,
    innings INT DEFAULT 0,
    runs INT DEFAULT 0,
    balls INT DEFAULT 0,
    average NUMERIC(5, 2) DEFAULT 0.00,
    strike_rate NUMERIC(6, 2) DEFAULT 0.00,
    fours INT DEFAULT 0,
    sixes INT DEFAULT 0,
    fifties INT DEFAULT 0,
    hundreds INT DEFAULT 0,
    highest_score INT DEFAULT 0,
    wickets INT DEFAULT 0,
    economy NUMERIC(5, 2) DEFAULT 0.00,
    bowling_average NUMERIC(5, 2) DEFAULT 0.00,
    bowling_strike_rate NUMERIC(5, 2) DEFAULT 0.00,
    five_wickets INT DEFAULT 0,
    best_figures VARCHAR(20) DEFAULT '0/0'
);

CREATE TABLE IF NOT EXISTS player_team_stats (
    player_id INT REFERENCES players(player_id) ON DELETE CASCADE,
    team_id INT REFERENCES teams(team_id) ON DELETE CASCADE,
    matches INT DEFAULT 0,
    innings INT DEFAULT 0,
    runs INT DEFAULT 0,
    balls INT DEFAULT 0,
    average NUMERIC(5, 2) DEFAULT 0.00,
    strike_rate NUMERIC(6, 2) DEFAULT 0.00,
    wickets INT DEFAULT 0,
    economy NUMERIC(5, 2) DEFAULT 0.00,
    PRIMARY KEY (player_id, team_id)
);

CREATE TABLE IF NOT EXISTS player_season_stats (
    player_id INT REFERENCES players(player_id) ON DELETE CASCADE,
    season_id VARCHAR(10) REFERENCES seasons(season_id) ON DELETE CASCADE,
    matches INT DEFAULT 0,
    innings INT DEFAULT 0,
    runs INT DEFAULT 0,
    balls INT DEFAULT 0,
    average NUMERIC(5, 2) DEFAULT 0.00,
    strike_rate NUMERIC(6, 2) DEFAULT 0.00,
    wickets INT DEFAULT 0,
    economy NUMERIC(5, 2) DEFAULT 0.00,
    PRIMARY KEY (player_id, season_id)
);

CREATE TABLE IF NOT EXISTS player_phase_stats (
    player_id INT REFERENCES players(player_id) ON DELETE CASCADE,
    phase VARCHAR(20), -- 'powerplay', 'middle', 'death'
    batting_runs INT DEFAULT 0,
    batting_balls INT DEFAULT 0,
    batting_strike_rate NUMERIC(6, 2) DEFAULT 0.00,
    bowling_runs INT DEFAULT 0,
    bowling_balls INT DEFAULT 0,
    bowling_wickets INT DEFAULT 0,
    bowling_economy NUMERIC(5, 2) DEFAULT 0.00,
    PRIMARY KEY (player_id, phase)
);

CREATE TABLE IF NOT EXISTS player_matchups (
    batter_id INT REFERENCES players(player_id) ON DELETE CASCADE,
    bowler_id INT REFERENCES players(player_id) ON DELETE CASCADE,
    runs INT DEFAULT 0,
    balls INT DEFAULT 0,
    dismissals INT DEFAULT 0,
    strike_rate NUMERIC(6, 2) DEFAULT 0.00,
    average NUMERIC(5, 2) DEFAULT 0.00,
    PRIMARY KEY (batter_id, bowler_id)
);

CREATE TABLE IF NOT EXISTS venue_intelligence (
    venue_id INT PRIMARY KEY REFERENCES venues(venue_id) ON DELETE CASCADE,
    matches INT DEFAULT 0,
    avg_1st_innings NUMERIC(5, 2) DEFAULT 0.00,
    avg_2nd_innings NUMERIC(5, 2) DEFAULT 0.00,
    batting_first_win_pct NUMERIC(5, 2) DEFAULT 0.00,
    chasing_win_pct NUMERIC(5, 2) DEFAULT 0.00,
    pitch_type VARCHAR(50) DEFAULT 'Balanced'
);

CREATE TABLE IF NOT EXISTS team_intelligence (
    team_id INT PRIMARY KEY REFERENCES teams(team_id) ON DELETE CASCADE,
    matches INT DEFAULT 0,
    wins INT DEFAULT 0,
    losses INT DEFAULT 0,
    win_pct NUMERIC(5, 2) DEFAULT 0.00,
    titles INT DEFAULT 0,
    avg_score NUMERIC(5, 2) DEFAULT 0.00,
    avg_economy NUMERIC(5, 2) DEFAULT 0.00
);

CREATE TABLE IF NOT EXISTS auction_roi (
    player_id INT PRIMARY KEY REFERENCES players(player_id) ON DELETE CASCADE,
    base_price NUMERIC(5, 2), -- in Lakhs
    sale_price NUMERIC(5, 2), -- in Crores
    bought_by_team_id INT REFERENCES teams(team_id) ON DELETE SET NULL,
    form INT,
    clutch INT,
    versatility INT,
    expected_value NUMERIC(5, 2), -- in Crores
    roi_multiplier NUMERIC(5, 2) -- expected_value / sale_price
);

-- -----------------------------------------------------------------------------
-- ANALYTICS VIEWS
-- -----------------------------------------------------------------------------

DROP VIEW IF EXISTS analytics_player_context;
CREATE VIEW analytics_player_context AS
SELECT
    p.player_id,
    p.name AS player_name,
    p.country,
    p.batting_style,
    p.bowling_style,
    pth.team_id,
    t.short_name AS team_short_name,
    pth.season_id,
    pth.start_season_id,
    pth.end_season_id,
    pth.current_team,
    cs.season_id AS current_squad_season,
    cs.role AS current_squad_role,
    pth.squad_role,
    pth.franchise_role,
    pth.representation_scope
FROM players p
LEFT JOIN player_team_history pth ON pth.player_id = p.player_id
LEFT JOIN teams t ON t.team_id = pth.team_id
LEFT JOIN current_squad cs ON cs.player_id = p.player_id AND cs.team_id = pth.team_id;

DROP VIEW IF EXISTS analytics_delivery_context;
CREATE VIEW analytics_delivery_context AS
SELECT
    d.delivery_id,
    d.match_id,
    d.innings_id,
    d.batter_id,
    d.bowler_id,
    d.batter_runs,
    d.extra_runs,
    d.total_runs,
    d.delivery_type,
    d.scoring_area,
    d.pressure_state,
    d.phase,
    d.current_rr,
    d.required_rr,
    m.season_id,
    m.venue_id,
    m.match_type,
    i.batting_team_id,
    i.bowling_team_id
FROM deliveries d
JOIN innings i ON i.innings_id = d.innings_id
JOIN matches m ON m.match_id = d.match_id;

DROP VIEW IF EXISTS analytics_team_context;
CREATE VIEW analytics_team_context AS
SELECT
    m.match_id,
    m.season_id,
    m.venue_id,
    m.match_type,
    m.team1_id,
    m.team2_id,
    m.winner_id,
    t1.short_name AS team1_short_name,
    t2.short_name AS team2_short_name
FROM matches m
LEFT JOIN teams t1 ON t1.team_id = m.team1_id
LEFT JOIN teams t2 ON t2.team_id = m.team2_id;


-- -----------------------------------------------------------------------------
-- CONTENT TABLES
-- -----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS articles (
    article_id SERIAL PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    excerpt TEXT,
    content TEXT,
    tag VARCHAR(50),
    read_time VARCHAR(20),
    published_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS reports (
    report_id SERIAL PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    tag VARCHAR(50),
    frequency VARCHAR(50),
    file_url VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS feed_events (
    event_id SERIAL PRIMARY KEY,
    match_id VARCHAR(50) REFERENCES matches(match_id) ON DELETE CASCADE,
    time VARCHAR(20),
    type VARCHAR(50), -- 'score', 'alert', 'momentum', 'ai', 'info'
    message TEXT NOT NULL,
    icon VARCHAR(50) -- lucide icon name
);

CREATE TABLE IF NOT EXISTS ai_insights (
    insight_id SERIAL PRIMARY KEY,
    match_id VARCHAR(50) REFERENCES matches(match_id) ON DELETE CASCADE,
    title VARCHAR(150) NOT NULL,
    insight TEXT NOT NULL,
    confidence INT NOT NULL CHECK (confidence >= 0 AND confidence <= 100)
);

CREATE TABLE IF NOT EXISTS pulse_events (
    pulse_id SERIAL PRIMARY KEY,
    match_id VARCHAR(50) REFERENCES matches(match_id) ON DELETE CASCADE,
    over_num INT NOT NULL,
    team1_momentum INT CHECK (team1_momentum >= 0 AND team1_momentum <= 100),
    team2_momentum INT CHECK (team2_momentum >= 0 AND team2_momentum <= 100),
    excitement INT CHECK (excitement >= 0 AND excitement <= 100),
    anxiety INT CHECK (anxiety >= 0 AND anxiety <= 100),
    shock INT CHECK (shock >= 0 AND shock <= 100),
    hope INT CHECK (hope >= 0 AND hope <= 100),
    CONSTRAINT unique_pulse_over UNIQUE (match_id, over_num)
);

-- -----------------------------------------------------------------------------
-- SYSTEM TABLES
-- -----------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS users (
    user_id SERIAL PRIMARY KEY,
    username VARCHAR(100) UNIQUE NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS saved_queries (
    query_id SERIAL PRIMARY KEY,
    user_id INT REFERENCES users(user_id) ON DELETE CASCADE,
    name VARCHAR(100) NOT NULL,
    filters JSONB NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS query_history (
    history_id SERIAL PRIMARY KEY,
    user_id INT REFERENCES users(user_id) ON DELETE CASCADE,
    filters JSONB NOT NULL,
    executed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS favorites (
    favorite_id SERIAL PRIMARY KEY,
    user_id INT REFERENCES users(user_id) ON DELETE CASCADE,
    target_type VARCHAR(50) NOT NULL, -- 'player', 'team', 'venue'
    target_id VARCHAR(50) NOT NULL, -- ID of target
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT unique_user_favorite UNIQUE (user_id, target_type, target_id)
);

-- -----------------------------------------------------------------------------
-- INDEXES & PERFORMANCE OPTIMIZATIONS
-- -----------------------------------------------------------------------------

-- Deliveries Indexes (Critical for ball-by-ball queries)
CREATE INDEX IF NOT EXISTS idx_deliveries_match_innings ON deliveries(match_id, innings_id);
CREATE INDEX IF NOT EXISTS idx_deliveries_innings ON deliveries(innings_id);
CREATE INDEX IF NOT EXISTS idx_deliveries_batter ON deliveries(batter_id);
CREATE INDEX IF NOT EXISTS idx_deliveries_bowler ON deliveries(bowler_id);
CREATE INDEX IF NOT EXISTS idx_deliveries_filter_lookup ON deliveries(match_id, over_num, ball_num);
CREATE INDEX IF NOT EXISTS idx_deliveries_match_id ON deliveries(match_id);

-- Match Indexes
CREATE INDEX IF NOT EXISTS idx_matches_season ON matches(season_id);
CREATE INDEX IF NOT EXISTS idx_matches_teams ON matches(team1_id, team2_id);
CREATE INDEX IF NOT EXISTS idx_matches_venue_id ON matches(venue_id);
CREATE INDEX IF NOT EXISTS idx_matches_team1_id ON matches(team1_id);
CREATE INDEX IF NOT EXISTS idx_matches_team2_id ON matches(team2_id);

-- Innings Indexes (joined on every stats-query aggregation)
CREATE INDEX IF NOT EXISTS idx_innings_match ON innings(match_id);
CREATE INDEX IF NOT EXISTS idx_innings_batting_team ON innings(batting_team_id);
CREATE INDEX IF NOT EXISTS idx_innings_bowling_team ON innings(bowling_team_id);

-- Wickets/Dismissals Indexes
CREATE INDEX IF NOT EXISTS idx_dismissals_delivery ON dismissals(delivery_id);
CREATE INDEX IF NOT EXISTS idx_dismissals_player_out ON dismissals(player_out_id);

-- Precomputed Stats Indexes (Fast lookup)
CREATE INDEX IF NOT EXISTS idx_player_career_avg ON player_career_stats(average);
CREATE INDEX IF NOT EXISTS idx_player_career_sr ON player_career_stats(strike_rate);
CREATE INDEX IF NOT EXISTS idx_player_team_lookup ON player_team_stats(team_id);
CREATE INDEX IF NOT EXISTS idx_player_season_lookup ON player_season_stats(season_id);

-- Squad History Indexes
CREATE INDEX IF NOT EXISTS idx_player_team_history_player ON player_team_history(player_id);
CREATE INDEX IF NOT EXISTS idx_player_team_history_team ON player_team_history(team_id);
CREATE INDEX IF NOT EXISTS idx_player_team_history_season ON player_team_history(season_id);
CREATE INDEX IF NOT EXISTS idx_current_squad_player ON current_squad(player_id);
CREATE INDEX IF NOT EXISTS idx_current_squad_team ON current_squad(team_id);
CREATE INDEX IF NOT EXISTS idx_clutch_index_player ON clutch_index(player_id);
CREATE INDEX IF NOT EXISTS idx_momentum_tracker_match ON momentum_tracker(match_id);
CREATE INDEX IF NOT EXISTS idx_partnership_stats_match ON partnership_stats(match_id);
CREATE INDEX IF NOT EXISTS idx_partnership_stats_batters ON partnership_stats(batter1_id, batter2_id);
